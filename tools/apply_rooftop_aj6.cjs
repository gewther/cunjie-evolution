const fs=require('fs');
const imageFile='dist/data/04-images.js';
const raw=fs.readFileSync(imageFile,'utf8');
const images=JSON.parse(raw.slice(raw.indexOf('=')+1).trim().replace(/;$/,''));
const previous=images.sneakersAJ6;
images.sneakersAJ6='data:image/png;base64,'+fs.readFileSync('dist/assets/rooftop/aj6.png').toString('base64');
if(!previous||previous===images.sneakersAJ6)throw Error('AJ6 image unchanged or missing');
fs.writeFileSync(imageFile,'DATA["images"]='+JSON.stringify(images)+';\n');
const engineFile='dist/data/touch-v1-impact.js';
const engineRaw=fs.readFileSync(engineFile,'utf8');
let html=JSON.parse(engineRaw.slice(engineRaw.indexOf('=')+1).trim().replace(/;$/,''));
const old="roomImg.src=roomKey==='rain'?'/assets/rooms/room-rain.webp':'/assets/rooms/room-warm.webp';";
const updated="roomImg.src=roomKey==='rooftop-day'?'/assets/rooftop/day.png':roomKey==='rooftop-night'?'/assets/rooftop/night.png':roomKey==='rain'?'/assets/rooms/room-rain.webp':'/assets/rooms/room-warm.webp';";
if(html.split(old).length!==2)throw Error('room selection anchor missing or ambiguous');
html=html.replace(old,updated);
html=html.replace("getItem('cunjie-room-theme')||'warm'","getItem('cunjie-room-theme')||'rooftop-day'");
fs.writeFileSync(engineFile,'DATA["storyLegacy"]='+JSON.stringify(html).replace(/</g,'\\u003c')+';\n');
const index='dist/impact.html'; let page=fs.readFileSync(index,'utf8');
const anchor='<option value="warm">午后暖光 · 新</option>';
if(page.split(anchor).length!==2)throw Error('room menu anchor missing or ambiguous');
page=page.replace(anchor,'<option value="rooftop-day" selected>屋顶球场 · 夕阳</option><option value="rooftop-night">屋顶球场 · 夜景</option>'+anchor);
fs.writeFileSync(index,page);
const room='dist/scripts/room-choice.js'; let choice=fs.readFileSync(room,'utf8');
choice=choice.replace("||'warm'","||'rooftop-day'"); fs.writeFileSync(room,choice);
console.log('AJ6 atlas and optional rooftop scenes installed');
