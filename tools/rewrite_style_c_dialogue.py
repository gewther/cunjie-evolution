def load_data(rel):
    p = os.path.join(ROOT, rel)
    raw = open(p, "r", encoding="utf-8").read()
    eq = raw.index("=")
    return raw[: eq + 1], json.loads(raw[eq + 1 :].strip().rstrip(";"))


def save_data(rel, prefix, obj, compact=False):
    p = os.path.join(ROOT, rel)
    sep = (",", ":") if compact else None
    payload = json.dumps(obj, ensure_ascii=False, separators=sep)
    if isinstance(obj, str):
        payload = payload.replace("<", "\\u003c")
    out = f"{prefix}{payload};\n"
    with open(p, "w", encoding="utf-8") as f:
        f.write(out)
    res = subprocess.run(["node", "--check"], input=out, text=True, capture_output=True)
    if res.returncode != 0:
        raise RuntimeError(f"Syntax check failed for {rel}: {res.stderr}")


def check_html_scripts(html_str, label):
    for m in re.finditer(r"<script[^>]*>([\s\S]*?)</script>", html_str):
        res = subprocess.run(["node", "--check"], input=m.group(1), text=True, capture_output=True)
        if res.returncode != 0:
            raise RuntimeError(f"Inner <script> syntax check failed in {label}: {res.stderr}")


