def update_original_and_sync():
    prefix, orig = load_data("dist/data/03-original.js")
    orig["stageNames"] = ORIGINAL_REPLACEMENT["stageNames"]
    old_to_new = {}
    all_new_lines = []
    old_stage_names = list(orig["stageNames"])  # capture before overwrite? reload cleanly:
    _, orig_disk = load_data("dist/data/03-original.js")
    old_names = orig_disk["stageNames"]
    old_tones = [st["tone"] for st in orig_disk["stages"]]

    for si in range(3):
        orig["stages"][si]["tone"] = ORIGINAL_REPLACEMENT["tones"][si]
        ev_map = orig["stages"][si]["events"]
        rep_map = ORIGINAL_REPLACEMENT["stages"][si]
        assert set(ev_map.keys()) == set(rep_map.keys()), f"Event keys mismatch at stage {si}"
        for ev, new_lines in rep_map.items():
            old_lines = ev_map[ev]["lines"]
            assert len(old_lines) == len(new_lines) == 3, f"Length mismatch {si}/{ev}"
            for ol, nl in zip(old_lines, new_lines):
                assert ol not in old_to_new, f"Duplicate old line: {ol}"
                old_to_new[ol] = nl
                all_new_lines.append(nl)
            ev_map[ev]["lines"] = new_lines

    assert len(all_new_lines) == 180 and len(set(all_new_lines)) == 180, "180 new lines must all be unique!"
    save_data("dist/data/03-original.js", prefix, orig)
    print("Updated dist/data/03-original.js (180 unique lines)")

    for rel in ("dist/data/touch-v1-impact.js", "dist/data/touch-v1-free.js"):
        bpref, bhtml = load_data(rel)
        # Update embedded XL_DIALOGUES header stageNames & tones as well
        bhtml = bhtml.replace(json.dumps(old_names, ensure_ascii=False), json.dumps(ORIGINAL_REPLACEMENT["stageNames"], ensure_ascii=False))
        # Update each stage's copied tone precisely inside XL_DIALOGUES
        xl_pos = bhtml.index("const XL_DIALOGUES=")
        xl_head = bhtml[:xl_pos]
        xl_tail = bhtml[xl_pos:]
        for si in range(3):
            target_tone = f'"tone": {json.dumps(old_tones[si], ensure_ascii=False)}'
            new_tone = f'"tone": {json.dumps(ORIGINAL_REPLACEMENT["tones"][si], ensure_ascii=False)}'
            assert target_tone in xl_tail, f"Missing old tone in {rel} stage {si}"
            xl_tail = xl_tail.replace(target_tone, new_tone, 1)
        bhtml = xl_head + xl_tail

        for ol, nl in old_to_new.items():
            cnt = bhtml.count(ol)
            assert cnt == 1, f"{rel}: expected 1 occurrence of '{ol}', got {cnt}"
            bhtml = bhtml.replace(ol, nl, 1)
        check_html_scripts(bhtml, rel)
        save_data(rel, bpref, bhtml)
        print(f"Synced 180 Style-C lines + stageNames/tones into {rel}")


